-- 2. sessions: anonymous browser sessions (id is generated by the browser)
create table public.sessions (
  id           uuid primary key,
  created_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

-- 3. scenarios: a named, saved set of inputs belonging to one session
create table public.scenarios (
  id         uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.sessions (id) on delete cascade,
  name       text not null check (char_length(name) between 1 and 60),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (session_id, name)
);

-- 4. scenario_values: one value per parameter, stored exactly as typed (e.g. "4.50"); '' = not set
create table public.scenario_values (
  scenario_id    uuid not null references public.scenarios (id) on delete cascade,
  parameter_code text not null references public.parameters (code),
  value          text not null default '' check (char_length(value) <= 32),
  primary key (scenario_id, parameter_code)
);

create index scenario_values_parameter_idx on public.scenario_values (parameter_code);

create function public.set_updated_at() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger scenarios_set_updated_at
  before update on public.scenarios
  for each row execute function public.set_updated_at();

-- Lock down: only the backend (service role) can read or write.
alter table public.parameters      enable row level security;
alter table public.sessions        enable row level security;
alter table public.scenarios       enable row level security;
alter table public.scenario_values enable row level security;
revoke all on public.parameters, public.sessions, public.scenarios, public.scenario_values
  from anon, authenticated;

-- Atomic writes (PostgREST cannot span tables in one transaction).
-- Both return jsonb: {"status": "ok" | "limit" | "name_taken" | "not_found", "id": <uuid>}.
create function public.create_scenario(p_session uuid, p_name text, p_values jsonb)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_id uuid;
begin
  insert into public.sessions (id) values (p_session)
    on conflict (id) do update set last_seen_at = now();

  if (select count(*) from public.scenarios where session_id = p_session) >= 50 then
    return jsonb_build_object('status', 'limit');
  end if;

  begin
    insert into public.scenarios (session_id, name) values (p_session, p_name) returning id into v_id;
  exception when unique_violation then
    return jsonb_build_object('status', 'name_taken');
  end;

  insert into public.scenario_values (scenario_id, parameter_code, value)
    select v_id, key, value from jsonb_each_text(p_values);
  return jsonb_build_object('status', 'ok', 'id', v_id);
end;
$$;

create function public.update_scenario(p_session uuid, p_id uuid, p_name text, p_values jsonb)
returns jsonb
language plpgsql
set search_path = ''
as $$
begin
  update public.sessions set last_seen_at = now() where id = p_session;

  begin
    update public.scenarios set name = p_name where id = p_id and session_id = p_session;
  exception when unique_violation then
    return jsonb_build_object('status', 'name_taken');
  end;
  if not found then
    return jsonb_build_object('status', 'not_found');
  end if;

  delete from public.scenario_values where scenario_id = p_id;
  insert into public.scenario_values (scenario_id, parameter_code, value)
    select p_id, key, value from jsonb_each_text(p_values);
  return jsonb_build_object('status', 'ok', 'id', p_id);
end;
$$;

revoke all on function public.create_scenario(uuid, text, jsonb) from public, anon, authenticated;
revoke all on function public.update_scenario(uuid, uuid, text, jsonb) from public, anon, authenticated;
grant execute on function public.create_scenario(uuid, text, jsonb) to service_role;
grant execute on function public.update_scenario(uuid, uuid, text, jsonb) to service_role;
