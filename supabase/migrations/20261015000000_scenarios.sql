-- Data model for saved scenarios (no user accounts; anonymous per-browser session id).
--
--   sessions --< scenarios --< scenario_values >-- parameters
--
-- Responsibilities: the database stores data and keeps it consistent. Validation rules and all
-- calculations live in the backend (backend/app/core); `parameters` mirrors the backend catalog
-- and the backend verifies it at startup. Results are never stored.
-- Only the backend (service-role key) touches these tables: RLS is on with no policies and all
-- privileges are revoked from the public API roles.

-- 1. parameters: catalog of the six loan inputs (reference data, written only by migrations)
create table public.parameters (
  code         text primary key,
  label        text    not null,
  kind         text    not null check (kind in ('money', 'percent', 'integer')),
  required     boolean not null,
  min_value    numeric not null,
  max_value    numeric not null check (max_value >= min_value),
  max_decimals int     not null check (max_decimals >= 0),
  sort_order   int     not null unique
);

